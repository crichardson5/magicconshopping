const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');
const root = path.resolve(__dirname, '..');
const ids = { alice: '00000000-0000-4000-8000-000000000001', bob: '00000000-0000-4000-8000-000000000002', outsider: '00000000-0000-4000-8000-000000000003' };
async function fixture() {
  const db = new PGlite();
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated;
    CREATE SCHEMA auth;
    CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    GRANT USAGE ON SCHEMA public,auth TO authenticated,anon;
    GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated,anon;
    CREATE TABLE public.checklist_members(user_id uuid PRIMARY KEY REFERENCES auth.users(id));
    ALTER TABLE public.checklist_members ENABLE ROW LEVEL SECURITY;
    GRANT SELECT ON public.checklist_members TO authenticated;
    CREATE POLICY "Read own membership" ON public.checklist_members FOR SELECT TO authenticated USING(user_id=auth.uid());
    INSERT INTO auth.users VALUES ('${ids.alice}'),('${ids.bob}'),('${ids.outsider}');
    INSERT INTO public.checklist_members VALUES ('${ids.alice}'),('${ids.bob}');
    CREATE PUBLICATION supabase_realtime;`);
  // PGlite has gen_random_uuid built in but does not package pgcrypto. No application SQL is otherwise changed.
  const baseline = (await fs.readFile(path.join(root,'sql/supabase_modular_migration.sql'),'utf8')).replace('CREATE EXTENSION IF NOT EXISTS pgcrypto;', '');
  await db.exec(baseline);
  const legacyList = (await db.query('INSERT INTO shopping_lists(name,created_by) VALUES ($1,$2) RETURNING id', ['Existing wishlist',ids.alice])).rows[0].id;
  const legacy = (await db.query('INSERT INTO shopping_list_items(list_id,item_name,purchased,estimated_price,price_paid) VALUES ($1,$2,true,12.34,10) RETURNING *',[legacyList,'Legacy card'])).rows[0];
  const migration = await fs.readFile(path.join(root,'sql/20261108_list_management.sql'),'utf8');
  await db.exec(migration);
  await db.exec(migration);
  let queue = Promise.resolve();
  const asUser = (user, sql, params = [], role = 'authenticated') => {
    const op = queue.then(() => db.transaction(async tx => {
      await tx.exec('SET LOCAL ROLE ' + role);
      await tx.query("SELECT set_config('request.jwt.claim.sub',$1,true)", [user || '']);
      return tx.query(sql,params);
    }));
    queue = op.catch(() => {});
    return op;
  };
  return { db, asUser, legacy, legacyList, migration };
}
async function databaseTests(f) {
  const { db, asUser, legacy, legacyList } = f;
  const get = async id => (await asUser(ids.alice,'SELECT * FROM shopping_list_items WHERE id=$1',[id])).rows[0];
  const existing = await get(legacy.id);
  for (const key of Object.keys(legacy)) assert.deepEqual(existing[key],legacy[key], 'Legacy field preserved: ' + key);
  assert.equal(existing.purchased_by,null);
  assert.equal(existing.purchased_at,null);
  const empty = (await asUser(ids.alice,'SELECT create_shopping_list($1,$2) id',['Empty','[]'])).rows[0].id;
  assert.equal((await asUser(ids.alice,'SELECT * FROM shopping_list_items WHERE list_id=$1',[empty])).rows.length,0);
  const card = { name:'Sol Ring',qty:2,deck:'Main',note:'',colorIdentity:[],setCode:'cmm',collectorNumber:'396' };
  const item = (await asUser(ids.alice,'SELECT add_shopping_list_item($1,$2,true) id',[empty,JSON.stringify(card)])).rows[0].id;
  const merged = (await asUser(ids.bob,'SELECT add_shopping_list_item($1,$2,true) id',[empty,JSON.stringify(card)])).rows[0].id;
  assert.equal(item,merged); assert.equal((await get(item)).quantity,4);
  const separate = (await asUser(ids.bob,'SELECT add_shopping_list_item($1,$2,false) id',[empty,JSON.stringify(card)])).rows[0].id;
  assert.notEqual(separate,item);
  await asUser(ids.alice,'UPDATE shopping_list_items SET purchased=true,purchased_by=$2,purchased_at=$3 WHERE id=$1',[item,ids.bob,'2000-01-01']);
  const bought = await get(item);
  assert.equal(bought.purchased_by,ids.alice); assert.ok(new Date(bought.purchased_at).getUTCFullYear()>2000);
  await asUser(ids.bob,'UPDATE shopping_list_items SET purchased_by=$2,purchased_at=$3,estimated_price=2.50 WHERE id=$1',[item,ids.bob,'2000-01-01']);
  assert.equal((await get(item)).purchased_by,ids.alice); assert.deepEqual((await get(item)).purchased_at,bought.purchased_at);
  await asUser(ids.bob,'UPDATE shopping_list_items SET purchased=false WHERE id=$1',[item]);
  assert.equal((await get(item)).purchased_by,null); assert.equal((await get(item)).purchased_at,null);
  await asUser(ids.bob,'UPDATE shopping_list_items SET purchased=true WHERE id=$1',[item]);
  assert.equal((await get(item)).purchased_by,ids.bob);
  await asUser(ids.alice,'INSERT INTO wishclaw_profiles VALUES ($1,$2)',[ids.alice,'Alice']);
  await asUser(ids.bob,'INSERT INTO wishclaw_profiles VALUES ($1,$2)',[ids.bob,'Bob']);
  assert.equal((await asUser(ids.bob,'SELECT * FROM wishclaw_profiles')).rows.length,2);
  assert.equal((await asUser(ids.bob,'UPDATE wishclaw_profiles SET display_name=$1 WHERE user_id=$2 RETURNING *',['Impersonator',ids.alice])).rows.length,0);
  await assert.rejects(asUser(ids.outsider,'INSERT INTO wishclaw_profiles VALUES ($1,$2)',[ids.outsider,'Outsider']));
  await assert.rejects(asUser(ids.alice,'UPDATE shopping_list_items SET list_id=$2 WHERE id=$1',[item,legacyList]));
  await assert.rejects(asUser(ids.outsider,'SELECT create_shopping_list($1,$2)',['Unauthorized','[]']));
  await assert.rejects(asUser(null,'SELECT create_shopping_list($1,$2)',['Anonymous','[]'],'anon'));
  await assert.rejects(asUser(ids.outsider,'SELECT add_shopping_list_item($1,$2,false)',[empty,JSON.stringify(card)]));
  await assert.rejects(asUser(ids.outsider,'INSERT INTO shopping_list_items(list_id,item_name) VALUES($1,$2)',[empty,'Unauthorized']));
  assert.equal((await asUser(ids.outsider,'SELECT * FROM shopping_lists')).rows.length,0);
  assert.equal((await asUser(ids.outsider,'SELECT * FROM wishclaw_profiles')).rows.length,0);
  assert.equal((await asUser(ids.outsider,'UPDATE shopping_list_items SET purchased=false WHERE id=$1 RETURNING id',[item])).rows.length,0);
  assert.equal((await asUser(ids.outsider,'DELETE FROM shopping_list_items WHERE id=$1 RETURNING id',[item])).rows.length,0);
  assert.equal((await asUser(ids.bob,'DELETE FROM shopping_lists WHERE id=$1 RETURNING id',[empty])).rows.length,0);
  const before = (await asUser(ids.alice,'SELECT count(*) FROM shopping_lists')).rows[0].count;
  await assert.rejects(asUser(ids.alice,'SELECT create_shopping_list($1,$2)',['Should roll back',JSON.stringify([card,{name:'Bad',qty:0}]) ]));
  assert.equal((await asUser(ids.alice,'SELECT count(*) FROM shopping_lists')).rows[0].count,before);
  await assert.rejects(asUser(ids.alice,'SELECT add_shopping_list_item($1,$2,false)',[empty,JSON.stringify({...card,colorIdentity:{bad:true}})]));
  await asUser(ids.bob,'DELETE FROM shopping_list_items WHERE id=$1',[separate]);
  assert.equal(await get(separate),undefined); assert.ok(await get(item));
  // Insert-time spoofing is covered separately from UPDATE transitions.
  const inserted = (await asUser(ids.alice,'INSERT INTO shopping_list_items(list_id,item_name,purchased,purchased_by) VALUES($1,$2,true,$3) RETURNING *',[empty,'Inserted purchase',ids.bob])).rows[0];
  assert.equal(inserted.purchased_by,ids.alice);
  const departed = '00000000-0000-4000-8000-000000000004';
  await db.query('INSERT INTO auth.users VALUES($1)',[departed]);
  await db.query('INSERT INTO checklist_members VALUES($1)',[departed]);
  const departedItem = (await asUser(departed,'INSERT INTO shopping_list_items(list_id,item_name,purchased) VALUES($1,$2,true) RETURNING *',[empty,'Departed member card'])).rows[0];
  await db.query('DELETE FROM checklist_members WHERE user_id=$1',[departed]);
  await db.query('DELETE FROM auth.users WHERE id=$1',[departed]);
  assert.equal((await get(departedItem.id)).purchased_by,null);
  assert.deepEqual((await get(departedItem.id)).purchased_at,departedItem.purchased_at);
  await db.exec(f.migration);
  assert.equal((await get(item)).purchased_by,ids.bob);
  assert.deepEqual((await get(legacy.id)).purchased_at,null);
  const publication = await db.query("SELECT tablename FROM pg_publication_tables WHERE pubname='supabase_realtime'");
  for (const table of ['shopping_lists','shopping_list_items','wishclaw_profiles']) assert.ok(publication.rows.some(row=>row.tablename===table));
  console.log('PASS: local PostgreSQL migration, repeatability, atomic create/add/merge/delete, attribution, profiles, RLS and legacy preservation');
}
module.exports={fixture,databaseTests,ids,root};
if(require.main===module) fixture().then(async f=>{try{await databaseTests(f)}finally{await f.db.close()}}).catch(e=>{console.error(e);process.exitCode=1});
